"""The deploy files agree with each other and with the code.

Railway builds the image from backend/Dockerfile with the repo root as the
context. A file the Dockerfile copies but .dockerignore leaves out, a lockfile
that drifted from requirements.txt, or a healthcheck path the app doesn't
serve all fail on Railway, minutes into a deploy. These checks fail here.
"""

from __future__ import annotations

import json
import re

from coach.api import create_app
from coach.config import Config
from conftest import BACKEND, ROOT

DOCKERFILE = BACKEND / "Dockerfile"


def _copies():
    sources = []
    for line in DOCKERFILE.read_text().splitlines():
        match = re.match(r"^COPY\s+(\S+)\s+\S+\s*$", line)
        if match:
            sources.append(match.group(1).rstrip("/"))
    return sources


def _admitted():
    patterns = [p.strip() for p in (ROOT / ".dockerignore").read_text().splitlines()
                if p.strip() and not p.startswith("#")]
    return patterns[0], [p[1:].rstrip("/") for p in patterns if p.startswith("!")]


def test_the_dockerignore_admits_exactly_what_the_dockerfile_copies():
    sources = _copies()
    assert sources == ["backend/requirements.lock", "backend/coach"]
    first, admitted = _admitted()
    assert first == "*", "start from nothing, so secrets can't slip into the build context"
    assert sorted(admitted) == sorted(sources)
    for source in sources:
        assert (ROOT / source).exists(), source
    assert not any(a.startswith(("backend/.env", ".pgdata", ".venv")) for a in admitted)


def test_the_image_has_what_the_service_reads_at_runtime_and_no_test_data():
    """The service reads only its own package at runtime; the fictional company stays with the tests."""
    assert (BACKEND / "coach" / "starter_criteria.csv").exists()
    text = DOCKERFILE.read_text()
    assert "WORKDIR /app/backend" in text and "COPY backend/coach ./coach" in text
    assert "pip install --require-hashes --no-deps -r requirements.lock" in text
    assert "USER coach" in text
    for leak in ("synthetic", "fixtures", "fernhill", "tests", "RECORDINGS"):
        assert leak not in text.lower().replace("requirements", ""), leak
    copied = [p for p in (BACKEND / "coach").rglob("*") if p.is_file() and "__pycache__" not in p.parts]
    assert not [p for p in copied if p.suffix not in (".py", ".csv")], copied
    assert [p.name for p in copied if p.suffix == ".csv"] == ["starter_criteria.csv"]


def test_the_seed_is_written_from_the_starter_criteria():
    """db/seed.sql is generated; a hand edit, or a starter change without a rewrite, fails here."""
    from coach.seed import seed_sql

    assert (ROOT / "db" / "seed.sql").read_text(encoding="utf-8") == seed_sql(), "run scripts/write_seed.py"
    text = seed_sql()
    assert "team_roles" not in text and "insert into calibrations" not in text and "jev_responses" not in text


def test_the_lockfile_pins_what_requirements_asks_for_with_hashes():
    lock = (BACKEND / "requirements.lock").read_text()
    entries = re.findall(r"^([A-Za-z0-9_.\-\[\]]+)==(\S+) \\\n((?:\s+--hash=sha256:[0-9a-f]{64}(?: \\)?\n)+)",
                         lock, re.MULTILINE)
    pinned = {re.sub(r"\[.*\]", "", name).lower().replace("_", "-"): version for name, version, _ in entries}
    assert len(entries) == len(re.findall(r"^[A-Za-z]", lock, re.MULTILINE)), "every pin carries hashes"
    for line in (BACKEND / "requirements.txt").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, version = line.split("==")
        assert pinned[re.sub(r"\[.*\]", "", name).lower().replace("_", "-")] == version.strip(), line
    resolved = re.search(r"autogenerated by pip-compile with Python (\d+\.\d+)", lock).group(1)
    assert "FROM python:{0}-slim".format(resolved) in DOCKERFILE.read_text()


def test_railway_setup_points_at_the_dockerfile_and_a_route_that_exists():
    """Railway reads no config file for new services: the README's variable and setting are the config."""
    readme = (ROOT / "README.md").read_text()
    path = re.search(r"\| `RAILWAY_DOCKERFILE_PATH` \| `([^`]+)` \|", readme).group(1)
    assert (ROOT / path).resolve() == DOCKERFILE.resolve()
    assert not (ROOT / "railway.json").exists(), "Railway ignores it for new services; don't imply otherwise"
    health = re.search(r"Healthcheck Path\*\* `([^`]+)`", readme).group(1)
    routes = {route.path for route in create_app(Config(auth_modes=("sheet_key",))).routes}
    assert health in routes and health == "/healthz"


def test_readme_links_resolve_and_prose_has_no_em_dashes():
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    assert "—" not in readme
    targets = re.findall(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", readme)
    local = [t for t in targets if not t.startswith(("http://", "https://", "mailto:"))]
    assert len(local) >= 6
    for target in local:
        assert (ROOT / target).exists(), target
    anchors = re.findall(r"\]\(#([a-z0-9-]+)\)", readme)
    headings = {re.sub(r"[^a-z0-9 -]", "", h.lower()).replace(" ", "-")
                for h in re.findall(r"^#{2,3} (.+)$", readme, re.MULTILINE)}
    for anchor in anchors:
        assert anchor in headings, anchor


def test_secrets_never_reach_the_railway_upload():
    railway = (ROOT / ".railwayignore").read_text().split()
    git = (ROOT / ".gitignore").read_text().split()
    for path in ("backend/.env", ".env", ".pgdata/", ".venv/"):
        assert path in railway, path
    assert "backend/.env" in git and ".env" in git


def test_apps_script_push_stages_one_deployment_and_leaves_the_templates_alone(tmp_path):
    import importlib.util

    spec = importlib.util.spec_from_file_location("push_apps_script", ROOT / "scripts" / "push_apps_script.py")
    push = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(push)
    script_id = "1" + "A" * 56
    written = push.stage(tmp_path, script_id, "https://coach-example.up.railway.app/")
    manifest = json.loads(written["appsscript.json"])
    template = json.loads((ROOT / "apps_script" / "appsscript.json").read_text())
    assert manifest["urlFetchWhitelist"] == ["https://coach-example.up.railway.app/"]
    assert manifest["oauthScopes"] == template["oauthScopes"]  # staging never widens access
    assert json.loads(written[".clasp.json"])["scriptId"] == script_id
    assert written["Code.gs"] == (ROOT / "apps_script" / "Code.gs").read_text()
    assert "REPLACE_WITH_YOUR_SCRIPT_ID" in (ROOT / "apps_script" / ".clasp.json").read_text()
    assert template["urlFetchWhitelist"] == ["https://YOUR-COACH-SERVICE.up.railway.app/"]
    for bad_id, url in (("short", "https://x.up.railway.app"), (script_id, "http://x.up.railway.app"),
                        (script_id, "https://x.up.railway.app/path")):
        try:
            push.stage(tmp_path, bad_id, url)
        except ValueError:
            continue
        raise AssertionError((bad_id, url))
